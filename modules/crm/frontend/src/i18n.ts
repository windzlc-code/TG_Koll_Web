export type Messages = (typeof catalog)[Language];

export function localizedError(error: unknown, messages: Messages): string {
  const candidate = error as { body?: { message_key?: string; code?: string }; message?: string } | null;
  const key = String(candidate?.body?.message_key || candidate?.body?.code || (candidate?.message?.startsWith("crm.errors.") ? candidate.message : ""));
  const errors = messages.errors as Record<string, string>;
  return errors[key] || (candidate?.message && !candidate.message.startsWith("crm.errors.") ? candidate.message : messages.dataError);
}

